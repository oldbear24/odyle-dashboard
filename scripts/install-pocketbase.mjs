import { mkdir, writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { execFileSync } from 'node:child_process';
import { resolve } from 'node:path';
const version = '0.40.5';
const platform = { win32: 'windows', linux: 'linux', darwin: 'darwin' }[process.platform];
const arch = { x64: 'amd64', arm64: 'arm64' }[process.arch];
if (!platform || !arch) throw new Error('Unsupported platform. Download PocketBase manually.');
const name = `pocketbase_${version}_${platform}_${arch}.zip`;
const base = `https://github.com/pocketbase/pocketbase/releases/download/v${version}/`;
const download = async (file) => { const res = await fetch(base + file); if (!res.ok) throw new Error(`Download failed: ${res.status}`); return Buffer.from(await res.arrayBuffer()); };
const [zip, sums] = await Promise.all([download(name), download('checksums.txt')]);
const expected = sums.toString().split('\n').find(line => line.endsWith(name))?.split(/\s+/)[0];
if (!expected || createHash('sha256').update(zip).digest('hex') !== expected) throw new Error('PocketBase checksum mismatch.');
await mkdir('.runtime', { recursive: true });
const archive = resolve('.runtime', name), destination = resolve('.runtime');
await writeFile(archive, zip);
if (process.platform === 'win32') execFileSync('powershell.exe', ['-NoProfile', '-Command', `Expand-Archive -LiteralPath '${archive.replaceAll("'", "''")}' -DestinationPath '${destination.replaceAll("'", "''")}' -Force`]);
else execFileSync('unzip', ['-o', archive, '-d', destination]);
console.log(`PocketBase ${version} installed; SHA-256 verified against the release checksums.`);
